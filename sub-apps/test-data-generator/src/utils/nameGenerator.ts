/** 获取中文文本的拼音（空格分隔） */
export function getTextPinyin(text: string): string {
  return text.split('').map(ch => PINYIN_MAP[ch] || ch).join(' ')
}

/** 生成中文姓名 + 拼音 */
export function generateNameWithPinyin(nameLength?: 2 | 3, ethnicity?: Ethnicity): { name: string; pinyin: string } {
  const name = generateName(nameLength, ethnicity)
  const pinyin = getTextPinyin(name)
  return { name, pinyin }
}

/** 批量生成中文姓名 */
export function generateNames(count: number, nameLength?: 2 | 3, ethnicity?: Ethnicity): string[] {
  const names = new Set<string>()
  while (names.size < count) {
    names.add(generateName(nameLength, ethnicity))
  }
  return Array.from(names)
}

/** 批量生成中文姓名（含拼音） */
export function generateNamesWithPinyin(count: number, nameLength?: 2 | 3, ethnicity?: Ethnicity): { name: string; pinyin: string }[] {
  const results: { name: string; pinyin: string }[] = []
  const seen = new Set<string>()
  while (seen.size < count) {
    const item = generateNameWithPinyin(nameLength, ethnicity)
    if (!seen.has(item.name)) {
      seen.add(item.name)
      results.push(item)
    }
  }
  return results
}
