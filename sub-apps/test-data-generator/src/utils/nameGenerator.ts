export type Ethnicity = 'han' | 'xinjiang' | 'tibetan' | 'random'

function randInt(min: number, max: number): number {
  return Math.floor(Math.random() * (max - min + 1)) + min
}

function pick<T>(arr: T[]): T {
  return arr[randInt(0, arr.length - 1)]
}

/** 生成中文姓名 */
export function generateName(nameLength?: 2 | 3, ethnicity?: Ethnicity): string {
  const resolved = ethnicity || 'han'
  if (resolved === 'xinjiang') return generateXinjiangName()
  if (resolved === 'tibetan') return generateTibetanName()
  // 汉族姓名
  const surname = pick(SURNAMES)
  const givenLen = nameLength || (Math.random() < 0.4 ? 2 : 1) // 40% 单名, 60% 双名
  let given = pick(GIVEN_NAMES)
  if (givenLen === 2) {
    given += pick(GIVEN_NAMES)
  }
  return surname + given
}

